/**
 * Build script to generate optimized icon bundles
 * This extracts only the icons actually used in the application
 * reducing the bundle from ~983KB to ~100-150KB
 *
 * Run: node scripts/build-optimized-icons.js
 */

import { promises as fs } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getIcons } from '@iconify/utils'

const __dirname = dirname(fileURLToPath(import.meta.url))

// Icons actually used in the application
// These lists are maintained in src/plugins/vuetify/icon-sets.js
import { usedMdiIcons, usedTablerIcons } from '../src/plugins/vuetify/icon-sets.js'

async function buildOptimizedIcons() {
  console.log('Building optimized icon bundles...')

  // Load full icon sets
  const mdiPath = join(__dirname, '../node_modules/@iconify-json/mdi/icons.json')
  const tablerPath = join(__dirname, '../node_modules/@iconify-json/tabler/icons.json')

  const mdiIconsFull = JSON.parse(await fs.readFile(mdiPath, 'utf8'))
  const tablerIconsFull = JSON.parse(await fs.readFile(tablerPath, 'utf8'))

  console.log(`Full MDI set: ${Object.keys(mdiIconsFull.icons).length} icons`)
  console.log(`Full Tabler set: ${Object.keys(tablerIconsFull.icons).length} icons`)

  // Extract only the icons we need
  const mdiIcons = getIcons(mdiIconsFull, usedMdiIcons)
  const tablerIcons = getIcons(tablerIconsFull, usedTablerIcons)

  if (!mdiIcons) {
    console.error('Failed to extract MDI icons')
    process.exit(1)
  }
  if (!tablerIcons) {
    console.error('Failed to extract Tabler icons')
    process.exit(1)
  }

  console.log(`Optimized MDI set: ${Object.keys(mdiIcons.icons).length} icons`)
  console.log(`Optimized Tabler set: ${Object.keys(tablerIcons.icons).length} icons`)

  // Check for missing icons
  const missingMdi = usedMdiIcons.filter(name => !mdiIcons.icons[name])
  const missingTabler = usedTablerIcons.filter(name => !tablerIcons.icons[name])

  if (missingMdi.length > 0) {
    console.warn('Warning: Missing MDI icons:', missingMdi)
  }
  if (missingTabler.length > 0) {
    console.warn('Warning: Missing Tabler icons:', missingTabler)
  }

  // Generate the optimized icons JS file
  const outputPath = join(__dirname, '../src/plugins/vuetify/icons-optimized.js')
  const content = `/**
 * AUTO-GENERATED FILE - DO NOT EDIT
 * Generated by scripts/build-optimized-icons.js
 *
 * This file contains only the icons actually used in the application.
 * To add new icons, update icon-sets.js and run: npm run build:icons
 */

// Optimized MDI icon set (${Object.keys(mdiIcons.icons).length} icons)
export const mdiIcons = ${JSON.stringify(mdiIcons)}

// Optimized Tabler icon set (${Object.keys(tablerIcons.icons).length} icons)
export const tablerIcons = ${JSON.stringify(tablerIcons)}
`

  await fs.writeFile(outputPath, content, 'utf8')

  // Calculate size savings
  const fullSize = JSON.stringify(mdiIconsFull).length + JSON.stringify(tablerIconsFull).length
  const optimizedSize = JSON.stringify(mdiIcons).length + JSON.stringify(tablerIcons).length
  const savings = ((1 - optimizedSize / fullSize) * 100).toFixed(1)

  console.log(`\nSaved to: ${outputPath}`)
  console.log(`Size reduction: ${(fullSize / 1024).toFixed(0)}KB -> ${(optimizedSize / 1024).toFixed(0)}KB (${savings}% smaller)`)
  console.log('\nDone!')
}

buildOptimizedIcons().catch(err => {
  console.error('Build failed:', err)
  process.exit(1)
})
